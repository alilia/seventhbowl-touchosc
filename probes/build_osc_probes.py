#!/usr/bin/env python3
"""
okuma interactive — OSC routing probes A, B, C for TouchOSC
===========================================================

Question: how does incoming OSC reach the scripts in TouchOSC?
  route R = the root script's onReceiveOSC
  route L = a LABEL with a receive-only OSC message on the address (like v4's
            status / battery labels), whose script forwards to the root with
            root:notify('osc:<address>', value) and returns true

    A  root script only, no receiver label        -> does R get /okuma/* at all?
    B  root + receiver label on /okuma/gaiwan,
       root onReceiveOSC returns FALSE            -> R? L? which first? cup1 via R?
    C  same as B, root returns TRUE               -> does L still get it?

    python build_osc_probes.py        # writes probe_A/B/C.tosc next to this file
    python build_osc_probes.py --receiver /okuma/cup1   # probe_B_cup1 / probe_C_cup1

Uses the XML helpers of ../build_okuma_layout.py (imported, not copied), so the
probes are built exactly like the real layout. Standard library only.
The scripts use only TouchOSC's restricted Lua 5.1 globals (see the template
header): ipairs pairs tostring type string table math + getMillis / root /
notify / findByName.
"""

import sys
import uuid
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import build_okuma_layout as B  # noqa: E402  (XML helpers: prop, label, button, text_box, rgba …)

ADDRS = ['/okuma/gaiwan', '/okuma/cup1']        # the load-cell module as it is today
RECEIVER_ADDR = '/okuma/gaiwan'                 # B / C: the only address with a receiver label
if '--receiver' in sys.argv:                    # e.g. --receiver /okuma/cup1 (only that cell connected)
    RECEIVER_ADDR = sys.argv[sys.argv.index('--receiver') + 1]
SUFFIX = '' if RECEIVER_ADDR == '/okuma/gaiwan' else '_' + RECEIVER_ADDR.rsplit('/', 1)[-1]

W, H = 1000, 720
BIG, MID, SMALL = 26, 18, 14


# ---------------------------------------------------------------------------
#  Root script (shared by A / B / C; two settings filled in per probe)
# ---------------------------------------------------------------------------
ROOT_LUA = r"""
-- okuma OSC routing probe @@PROBE@@  (generated by build_osc_probes.py)
-- R = root onReceiveOSC, L = receiver label (forwards via root:notify)
local PROBE        = '@@PROBE@@'
local ROOT_RETURNS = @@RETURNS@@          -- what root onReceiveOSC returns
local ADDRS        = { '/okuma/gaiwan', '/okuma/cup1' }
local SHORT        = { ['/okuma/gaiwan'] = 'g', ['/okuma/cup1'] = 'c' }

local n, pend, pairsRL, pairsLR, lastV, seq
local otherN, otherLast, firstMs, dirty, lastUi

local function reset()
  n, pend, lastV = {}, {}, {}
  pairsRL, pairsLR = {}, {}
  for _, a in ipairs(ADDRS) do
    n[a] = { R = 0, L = 0 }; pend[a] = { R = 0, L = 0 }
    pairsRL[a] = 0; pairsLR[a] = 0; lastV[a] = '—'
  end
  seq, otherN, otherLast, firstMs = {}, 0, '—', nil
  dirty, lastUi = true, 0
end

local function ctl(name) return root:findByName(name, true) end
local function setText(name, s)
  local c = ctl(name)
  if c and c.values.text ~= s then c.values.text = s end
end

-- one arrival on route ('R' or 'L')
local function note(route, path, v)
  if not firstMs then firstMs = getMillis() end
  local c = n[path]
  if not c then                       -- something else (other module, typo …)
    if route == 'R' then otherN = otherN + 1; otherLast = tostring(path) end
    dirty = true
    return
  end
  c[route] = c[route] + 1
  lastV[path] = tostring(v)
  -- pairing: the same message arriving on the other route too
  local p, other = pend[path], (route == 'R') and 'L' or 'R'
  if p[other] > 0 then
    p[other] = p[other] - 1
    if other == 'R' then pairsRL[path] = pairsRL[path] + 1
    else pairsLR[path] = pairsLR[path] + 1 end
  else
    p[route] = p[route] + 1
  end
  seq[#seq + 1] = SHORT[path] .. route
  while #seq > 14 do table.remove(seq, 1) end
  dirty = true
end

local function show()
  for i, a in ipairs(ADDRS) do
    local c = n[a]
    setText('row' .. i, string.format('%s    root %d    label %d', a, c.R, c.L))
    setText('row' .. i .. '_sub', string.format(
      'pairs root>label %d   label>root %d   unpaired R %d / L %d   last value %s',
      pairsRL[a], pairsLR[a], pend[a].R, pend[a].L, lastV[a]))
  end
  setText('seq', 'last arrivals (g=gaiwan c=cup1, R=root L=label):  ' .. table.concat(seq, ' '))
  local secs = firstMs and string.format('%.1f s since first', (getMillis() - firstMs) / 1000) or 'nothing yet'
  setText('other', string.format('other addresses at root: %d (last %s)    %s', otherN, otherLast, secs))
end

function init()
  reset()
  setText('mode', string.format('PROBE %s    root onReceiveOSC returns %s', PROBE, tostring(ROOT_RETURNS)))
  show()
end

function onReceiveOSC(message, connections)
  local a = message[2] and message[2][1]
  note('R', message[1], a and a.value)
  return ROOT_RETURNS
end

function onReceiveNotify(key, value)
  if key == 'probe_reset' then reset(); show(); return end
  local path = string.match(tostring(key), '^osc:(.+)$')
  if path then note('L', path, value) end
end

function update()
  local now = getMillis()
  if dirty and now - lastUi >= 100 then
    lastUi, dirty = now, false
    show()
  end
end
"""

# Receiver label script: v4's RECEIVER_SCRIPT plus its own visible counter, so
# the label route is seen even if the notify to the root were lost.
RECEIVER_LUA = r"""local count = 0
function onReceiveOSC(message, connections)
  count = count + 1
  self.values.text = 'receiver label ' .. tostring(message[1]) .. ' : own count ' .. count
  local a = message[2] and message[2][1]
  if a and type(a.value) == 'number' then
    root:notify('osc:' .. message[1], a.value)
  end
  return true   -- like v4: keep TouchOSC from writing the number into the label
end"""


def receiver_label(name, frame, path):
    """Same as v4's status label (B.label with osc_path) but with RECEIVER_LUA."""
    props = B.base_props(name, frame, B.rgba('#1f2a1f'), interactive=False, outline=False,
                         background=True) + B.text_props(MID, '#9fe09f', 0)
    props += B.prop('s', 'script', RECEIVER_LUA)
    return B.node('LABEL', props,
                  B.value('text', f'receiver label {path} : own count 0', 1) + B.TOUCH_VALUE,
                  B.osc_receive_message(path))


def instructions(probe):
    return (f'PROBE {probe}\n'
            '1  TouchOSC: Connections > OSC = UDP, receive port 10000 (TouchDesigner closed). '
            'Load this file, press Play (▶).\n'
            '2  Press RESET, then press and release the gaiwan cell ~10 times, then cup1 ~10 times.\n'
            '3  Read the two rows (root / label counts, pairs), the receiver line and the arrivals line.')


DESCRIPTION = {
    'A': 'root script only — no control receives /okuma/*',
    'B': f'root + receiver label on {RECEIVER_ADDR} — root returns false',
    'C': f'root + receiver label on {RECEIVER_ADDR} — root returns TRUE',
}


def build_probe(probe, with_receiver, root_returns):
    lua = ROOT_LUA.replace('@@PROBE@@', probe).replace('@@RETURNS@@', 'true' if root_returns else 'false')
    x, cw = 20, W - 40
    kids = [
        B.label('title', (x, 12, cw, 34), f'okuma OSC probe {probe}: {DESCRIPTION[probe]}', MID,
                '#e6c84d', align=0),
        B.label('mode', (x, 48, cw, 26), '—', SMALL, B.DIM_TEXT, align=0),
    ]
    y = 90
    for i, a in enumerate(ADDRS, 1):
        kids += [
            B.label(f'row{i}', (x, y, cw, 44), f'{a}    root 0    label 0', BIG, B.WHITE, align=0,
                    background='#1a1a1f'),
            B.label(f'row{i}_sub', (x, y + 46, cw, 24), '', SMALL, B.DIM_TEXT, align=0),
        ]
        y += 86
    if with_receiver:
        kids.append(receiver_label('receiver', (x, y, cw, 40), RECEIVER_ADDR))
    else:
        kids.append(B.label('receiver', (x, y, cw, 40), 'no receiver label in this probe', MID,
                            '#596169', align=0, background='#1a1a1f'))
    y += 52
    kids += [
        B.label('seq', (x, y, cw, 30), '', SMALL, B.WHITE, align=0),
        B.label('other', (x, y + 32, cw, 30), '', SMALL, B.DIM_TEXT, align=0),
    ]
    y += 80
    kids += B.labelled_button('probe_reset_btn', (x, y, 180, 60), '#7a2e2e', 'probe_reset',
                              [('reset_lbl', (0, 15, 30), 'RESET', 18, '#f2f2f2')])
    # button() notifies (key, its name); the root only looks at the key
    kids.append(B.text_box('howto', (x + 200, y, cw - 200, 150), instructions(probe), size=13))

    root_props = ''.join([
        B.prop('b', 'background', True), B.prop('c', 'color', B.rgba(B.BACKGROUND)),
        B.prop('f', 'cornerRadius', 1), B.prop('r', 'frame', (0, 0, W, H)),
        B.prop('b', 'grabFocus', False), B.prop('b', 'interactive', False),
        B.prop('b', 'locked', False), B.prop('s', 'name', f'okuma_probe_{probe}'),
        B.prop('i', 'orientation', 0), B.prop('b', 'outline', True),
        B.prop('i', 'outlineStyle', 0), B.prop('i', 'pointerPriority', 0),
        B.prop('s', 'script', lua), B.prop('i', 'shape', 1),
        B.prop('s', 'tag', ''), B.prop('b', 'visible', True),
    ])
    xml = ("<?xml version='1.0' encoding='UTF-8'?><lexml version='6'>"
           f"<node ID='{uuid.uuid4()}' type='GROUP'><includes></includes>"
           f'<properties>{root_props}</properties><values>{B.TOUCH_VALUE}</values>'
           f"<children>{''.join(kids)}</children></node></lexml>")
    return xml, lua


def main():
    out = HERE
    for probe, with_receiver, ret in (('A', False, False), ('B', True, False), ('C', True, True)):
        if SUFFIX and not with_receiver:
            continue                              # A has no receiver: unchanged
        xml, lua = build_probe(probe, with_receiver, ret)
        name = f'probe_{probe}{SUFFIX}'
        (out / f'{name}.tosc').write_bytes(zlib.compress(xml.encode('utf-8')))
        (out / f'{name}.lua').write_text(lua, encoding='utf-8')
        print(f'wrote {name}.tosc')
        continue
        (out / f'probe_{probe}.tosc').write_bytes(zlib.compress(xml.encode('utf-8')))
        (out / f'probe_{probe}.lua').write_text(lua, encoding='utf-8')
        if '--xml' in sys.argv:
            (out / f'probe_{probe}.xml').write_text(xml, encoding='utf-8')
        print(f'wrote probe_{probe}.tosc')


if __name__ == '__main__':
    main()
